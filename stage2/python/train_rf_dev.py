"""Train and evaluate the Stage 2 Random Forest on development-only data.

Run after prepare_dev_data.py:
    python stage2/python/train_rf_dev.py

Results from the synthetic development dataset are not thesis evidence.
"""
import json
import sys
from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, confusion_matrix, f1_score,
                             precision_score, recall_score, roc_auc_score)

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import reportlib as R

FEATURES = ["temperature", "humidity", "pir"]


def main():
    stage2 = ROOT / "stage2"
    data_dir = stage2 / "data"
    model_dir = stage2 / "models"
    report_dir = stage2 / "reports" / "phase_a"
    train = pd.read_csv(data_dir / "DEV_ONLY_train.csv")
    test = pd.read_csv(data_dir / "DEV_ONLY_test.csv")
    required_columns = set(FEATURES + ["anomaly"])
    if not required_columns.issubset(train.columns):
        raise ValueError("Development training CSV is missing required feature or label columns.")
    if not required_columns.issubset(test.columns):
        raise ValueError("Development test CSV is missing required feature or label columns.")

    classifier = RandomForestClassifier(
        n_estimators=200,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )
    classifier.fit(train[FEATURES], train["anomaly"])
    predicted = classifier.predict(test[FEATURES])
    anomaly_index = list(classifier.classes_).index(1)
    probability = classifier.predict_proba(test[FEATURES])[:, anomaly_index]
    matrix = confusion_matrix(test["anomaly"], predicted, labels=[0, 1])
    metrics = {
        "accuracy": float(accuracy_score(test["anomaly"], predicted)),
        "precision_anomaly": float(precision_score(test["anomaly"], predicted, zero_division=0)),
        "recall_anomaly": float(recall_score(test["anomaly"], predicted, zero_division=0)),
        "f1_anomaly": float(f1_score(test["anomaly"], predicted, zero_division=0)),
        "roc_auc": float(roc_auc_score(test["anomaly"], probability)),
        "threshold": 0.5,
        "test_rows": int(len(test)),
        "confusion_matrix_labels_0_1": matrix.tolist(),
    }

    model_path = model_dir / "DEV_ONLY_rf_classifier.joblib"
    joblib.dump({
        "warning": "DEVELOPMENT-ONLY synthetic model; not thesis evidence",
        "features": FEATURES,
        "model": classifier,
        "threshold": 0.5,
    }, model_path)

    figure_path = report_dir / "fig_dev_rf_confusion_matrix.png"
    figure, axis = plt.subplots(figsize=(3.7, 3.1))
    image = axis.imshow(matrix, cmap="Greys")
    axis.set(xticks=[0, 1], yticks=[0, 1], xticklabels=["normal", "anomaly"],
             yticklabels=["normal", "anomaly"], xlabel="Predicted", ylabel="Actual")
    for row in range(2):
        for column in range(2):
            axis.text(column, row, str(matrix[row, column]), ha="center", va="center")
    figure.colorbar(image, ax=axis, fraction=0.046, pad=0.04)
    R.savefig(str(figure_path))

    document = R.new_doc(
        "Stage 2 Phase A: Random Forest Baseline",
        "Held-out evaluation on development-only synthetic data",
        simulated=True,
    )
    document.add_heading("1. Method", 1)
    document.add_paragraph(
        "A class-weighted RandomForestClassifier was fitted on the 4,000-row training split. "
        "The 1,000-row test split was used only for evaluation. Features were temperature, humidity, and PIR; "
        "anomaly was the positive class. The decision threshold is 0.5."
    )
    R.table(document, ["Metric", "Held-out test"], [
        ["Accuracy", f"{metrics['accuracy']:.4f}"],
        ["Precision (anomaly)", f"{metrics['precision_anomaly']:.4f}"],
        ["Recall (anomaly)", f"{metrics['recall_anomaly']:.4f}"],
        ["F1 (anomaly)", f"{metrics['f1_anomaly']:.4f}"],
        ["ROC-AUC", f"{metrics['roc_auc']:.4f}"],
    ])
    R.picture(document, str(figure_path), "Confusion matrix; rows are actual labels, columns are predictions.", 3.8)
    document.add_heading("2. Interpretation limit", 1)
    document.add_paragraph(
        "These metrics describe a classifier evaluated against labels generated by the development simulator. "
        "They do not measure real-world sensor anomaly detection and must not be cited as thesis or paper results. "
        "Replace the development data with the project dataset before drawing performance conclusions."
    )
    document.save(report_dir / "S2_PhaseA_RF_Report_DEV_ONLY.docx")

    summary = {
        "warning": "DEVELOPMENT-ONLY SYNTHETIC DATA. Do not cite in thesis or paper.",
        "model": "RandomForestClassifier",
        "n_estimators": 200,
        "class_weight": "balanced",
        "random_state": 42,
        "feature_order": FEATURES,
        "train_rows": int(len(train)),
        "test_rows": int(len(test)),
        "metrics": metrics,
        "feature_importance": {name: float(value) for name, value in zip(FEATURES, classifier.feature_importances_)},
        "model_file": "stage2/models/DEV_ONLY_rf_classifier.joblib",
    }
    with open(report_dir / "DEV_ONLY_rf_summary.json", "w", encoding="utf-8") as file:
        json.dump(summary, file, indent=2)

    print("DEVELOPMENT-ONLY Random Forest baseline")
    for name, value in metrics.items():
        print(f"{name}: {value}")
    print(f"Report: {report_dir / 'S2_PhaseA_RF_Report_DEV_ONLY.docx'}")


if __name__ == "__main__":
    main()
